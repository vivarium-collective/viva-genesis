"""Study 31 — Protometabolism to Amphiphiles (does the membrane assemble + hold?).

Can metabolic products yield membrane-forming amphiphile mixtures? This composite
drives a REAL Martini 3 CG MD (viva-openmm's OpenMMMartiniProcess) on a POPE
bilayer generated by viva_genesis.membranes.martini_bilayer, and reports membrane
COHESION: minimization + NVT relaxes the hand-placed (clashy) amphiphiles into a
bound bilayer, so the potential energy drops to a stable negative value — the
assembly signal. Reports potential/kinetic energy (cohesion) + the static area per
lipid + lipid count.

Decision test (plan): the model reaches an experimental assembly window without
exogenous amphiphiles — i.e. the amphiphiles cohere into a stable membrane (PE
settles negative, membrane intact). The charged-intermediate PERMEABILITY closure
the plan also names needs a free-energy (PMF/umbrella) calculation and is the
documented next step on top of this engine — not an NVT observable.

Requires the ``membrane`` extra (viva-openmm + OpenMM + martini_openmm). Without
it the generator still registers; the run raises a clear ImportError.
"""
from __future__ import annotations

import os
import tempfile

from process_bigraph.composite_generator import composite_generator

from ..core import build_core
from ..membranes.martini_bilayer import build_pope_bilayer


@composite_generator(
    name="og_31_protometabolism_to_amphiphiles",
    methods=["Martini 3 coarse-grained MD (OpenMM + martini_openmm)",
             "generated POPE bilayer system", "membrane cohesion via minimize+NVT"],
    fidelity="real",
    description=(
        "Study 31: do amphiphiles assemble into a membrane? Drives real Martini 3 CG MD "
        "(viva-openmm) on a generated POPE bilayer; minimize+NVT relaxes the clashy initial "
        "placement into a bound bilayer so the potential energy settles negative — the "
        "membrane-cohesion / assembly signal. Reports PE/KE (cohesion), static area-per-lipid "
        "and lipid count. Charged-intermediate permeability (PMF) is the documented follow-up."
    ),
    parameters={
        "nx": {"type": "integer", "default": 4, "description": "Lipids per leaflet in x"},
        "ny": {"type": "integer", "default": 4, "description": "Lipids per leaflet in y"},
        "temperature": {"type": "float", "default": 310.0, "description": "Thermostat (K)"},
        "steps_per_update": {"type": "integer", "default": 500,
                             "description": "MD steps per composite tick"},
        "platform": {"type": "string", "default": "OpenCL",
                     "description": "OpenMM platform (OpenCL=Metal GPU; CPU/Reference also valid)"},
        "minimize": {"type": "boolean", "default": True,
                     "description": "Energy-minimize the clashy initial placement first"},
    },
    default_n_steps=20,
    preferred_time="10 nanoseconds",
    core_extensions=[build_core],
    emitters=[{"address": "local:ParquetEmitter",
               "paths": ["md/potential_energy", "md/kinetic_energy",
                         "membrane/area_per_lipid", "membrane/n_lipids"]}],
)
def og_31_protometabolism_to_amphiphiles(core=None, *, nx=4, ny=4, temperature=310.0,
                                         steps_per_update=500, platform="OpenCL", minimize=True):
    if core is None:
        core = build_core()

    # Generate the Martini bilayer system (gro/top) the MD runs on. Written to a
    # per-build temp dir; regenerated deterministically each run (incl. the
    # dashboard subprocess), so the files always exist for OpenMMMartiniProcess.
    out_dir = tempfile.mkdtemp(prefix="og31_bilayer_")
    bilayer = build_pope_bilayer(out_dir, nx=int(nx), ny=int(ny))

    return {
        "md_process": {
            "_type": "process",
            "address": "local:OpenMMMartiniProcess",
            "config": {
                "gro": bilayer.gro_path,
                "top": bilayer.top_path,
                "temperature": float(temperature),
                "platform": str(platform),
                "steps_per_update": int(steps_per_update),
                "minimize": bool(minimize),
            },
            "interval": 1.0,
            "inputs": {"temperature": ["env", "temperature"]},
            "outputs": {"potential_energy": ["md", "potential_energy"],
                        "kinetic_energy": ["md", "kinetic_energy"],
                        "n_steps": ["md", "n_steps"]},
        },
        "env": {"temperature": float(temperature)},
        "md": {"potential_energy": 0.0, "kinetic_energy": 0.0, "n_steps": 0},
        # Static membrane geometry (the generated bilayer), emitted alongside the MD.
        "membrane": {"area_per_lipid": float(bilayer.area_per_lipid_nm2),
                     "n_lipids": float(bilayer.n_lipids)},
        "emitter": {
            "_type": "step",
            "address": "local:RAMEmitter",
            "config": {"emit": {"potential_energy": "float", "kinetic_energy": "float",
                                "area_per_lipid": "float", "n_lipids": "float"}},
            "inputs": {"potential_energy": ["md", "potential_energy"],
                       "kinetic_energy": ["md", "kinetic_energy"],
                       "area_per_lipid": ["membrane", "area_per_lipid"],
                       "n_lipids": ["membrane", "n_lipids"]},
        },
    }
